  await search(page).fill('ふたたびチョコレート')
  await results(page).locator('[data-search-kind="live"]').first().click()
  await expect(page.locator('.live-page')).toHaveAttribute('data-live-unit', '2026-09-30-okashi-bokuso')
  await expect(page.locator('.live-source-quote mark.search-hit').first()).toBeInViewport()
  await page.getByRole('button', { name: '検索をクリア', exact: true }).click()
  await expect(page.locator('[data-live-group]')).toHaveCount(28)
  await expect(page.locator('.live-page mark')).toHaveCount(0)
  await page.getByLabel('选择学习单元', { exact: true }).selectOption('2026-09-28')
  await nav(page).getByRole('button', { name: '複合動詞', exact: true }).click()
